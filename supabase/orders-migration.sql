-- Run once in the Supabase SQL Editor to enable checkout and admin orders.
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_name text not null,
  phone text not null,
  address text not null,
  city text not null,
  notes text not null default '',
  subtotal integer not null check (subtotal >= 0),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipped', 'completed', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id text not null,
  product_name text not null,
  product_slug text not null,
  size text not null,
  quantity integer not null check (quantity between 1 and 99),
  unit_price integer not null check (unit_price >= 0)
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- No public policies: checkout and admin access run through protected server routes.
revoke all on public.orders from anon, authenticated;
revoke all on public.order_items from anon, authenticated;

-- The storefront may read catalog data; all catalog writes now use the server secret key.
revoke insert, update, delete on public.categories from anon, authenticated;
revoke insert, update, delete on public.subcategories from anon, authenticated;
revoke insert, update, delete on public.products from anon, authenticated;
revoke insert, update, delete on public.homepage_product_placements from anon, authenticated;

drop policy if exists "Categories public access" on public.categories;
drop policy if exists "Categories public read" on public.categories;
create policy "Categories public read" on public.categories for select to anon, authenticated using (true);
drop policy if exists "Subcategories public access" on public.subcategories;
drop policy if exists "Subcategories public read" on public.subcategories;
create policy "Subcategories public read" on public.subcategories for select to anon, authenticated using (true);
drop policy if exists "Products public access" on public.products;
drop policy if exists "Products public read" on public.products;
create policy "Products public read" on public.products for select to anon, authenticated using (true);
drop policy if exists "Homepage placements public access" on public.homepage_product_placements;
drop policy if exists "Homepage placements public read" on public.homepage_product_placements;
create policy "Homepage placements public read" on public.homepage_product_placements for select to anon, authenticated using (true);
